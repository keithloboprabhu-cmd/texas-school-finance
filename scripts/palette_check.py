"""Colour-vision check for the data palettes -> data/qa/palette_check.md.

Simulates deuteranopia and protanopia (Machado, Oliveira & Fernandes 2009, severity 1.0 matrices) and
grayscale (Rec. 709 luma), then reports the smallest CIE76 colour difference between any two classes.
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from ui.theme import BIVARIATE_3X3, DIVERGING_7, SEQUENTIAL_7  # noqa: E402

MACHADO = {
    "deuteranopia": np.array(
        [
            [0.367322, 0.860646, -0.227968],
            [0.280085, 0.672501, 0.047413],
            [-0.011820, 0.042940, 0.968881],
        ]
    ),
    "protanopia": np.array(
        [
            [0.152286, 1.052583, -0.204868],
            [0.114503, 0.786281, 0.099216],
            [-0.003882, -0.048116, 1.051998],
        ]
    ),
}


def hex2rgb(h):
    h = h.lstrip("#")
    return np.array([int(h[i : i + 2], 16) for i in (0, 2, 4)]) / 255


def lin(c):
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def delin(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, 12.92 * c, 1.055 * c ** (1 / 2.4) - 0.055)


def lab(rgb):
    x = (
        lin(rgb)
        @ np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]]).T
    )
    x = x / np.array([0.95047, 1.0, 1.08883])
    f = np.where(x > 0.008856, np.cbrt(x), 7.787 * x + 16 / 116)
    return np.array([116 * f[1] - 16, 500 * (f[0] - f[1]), 200 * (f[1] - f[2])])


def simulate(rgb, kind):
    if kind == "normal":
        return rgb
    if kind == "grayscale":
        y = rgb @ np.array([0.2126, 0.7152, 0.0722])
        return np.array([y, y, y])
    return delin(MACHADO[kind] @ lin(rgb))


def min_delta(colors, kind):
    labs = [lab(simulate(hex2rgb(c), kind)) for c in colors]
    return min(np.linalg.norm(a - b) for a, b in itertools.combinations(labs, 2))


def adjacent_delta(colors, kind):
    labs = [lab(simulate(hex2rgb(c), kind)) for c in colors]
    return min(np.linalg.norm(labs[i] - labs[i + 1]) for i in range(len(labs) - 1))


rows = []
for name, cols, fn in [
    ("Sequential (7)", SEQUENTIAL_7, adjacent_delta),
    ("Diverging (7)", DIVERGING_7, adjacent_delta),
    ("Bivariate 3x3", list(BIVARIATE_3X3.values()), min_delta),
]:
    rows.append(
        (
            name,
            fn.__name__.replace("_delta", ""),
            *[fn(cols, k) for k in ["normal", "deuteranopia", "protanopia", "grayscale"]],
        )
    )

out = [
    "# Palette colour-vision check",
    "",
    "Smallest CIE76 colour difference (Delta E) between classes after simulation. For ordered palettes the check is "
    "between adjacent classes; for the bivariate grid, between any two cells. Rough guide: Delta E > 10 is clearly "
    "distinguishable, 5-10 noticeable side by side, < 5 hard to tell apart.",
    "",
    "| Palette | Pairs | Normal | Deuteranopia | Protanopia | Grayscale |",
    "|---|---|---:|---:|---:|---:|",
]
out += [f"| {r[0]} | {r[1]} | {r[2]:.1f} | {r[3]:.1f} | {r[4]:.1f} | {r[5]:.1f} |" for r in rows]
out += [
    "",
    "The bivariate grid is not grayscale-safe (two cells can share a luminance); for print or grayscale use the "
    "Atlas single-metric view, whose palettes keep Delta E >= 10 between neighbouring classes.",
    "",
    "Every map also offers 'View as table', hover cards print exact values, and legends label each class, so "
    "no reading depends on colour alone. Generated by scripts/palette_check.py.",
]
Path(__file__).resolve().parent.parent.joinpath("data/qa/palette_check.md").write_text(
    "\n".join(out) + "\n"
)
print("\n".join(out))
